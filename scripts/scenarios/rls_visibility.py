#!/usr/bin/env python3
"""Row-level security must not shrink a snapshot silently (src/rls_guard.zig).

A chain object is a SELECT run by the reader role with `zb.tenant` set, so the reader's
policies decide which rows it holds. A policy that hides rows leaves a well-formed object
that reads exactly like one for a small or empty table. The guard refuses to publish for a
pair whose policy configuration it cannot prove complete, keeps the previous chain, says so
in the log, /metrics and `--diagnose`, and publishes again by itself once it is fixed.

A probe bridge runs on a NATS stack of its own (generated by `bridge --init-nats operator`,
booted here) against throwaway tables, at the minimum cadence. A healthy control table
shares the stack the whole time: unrelated pairs must keep publishing while another is
blocked.

  1. a valid configuration publishes: a tenant pair, and an untenanted EMPTY table (and a
     tenant pair whose only row is tombstoned) get a full with zero rows, not a block;
  2. `ALTER POLICY ... USING (false)` AFTER the bridge started: the pair is blocked
     (`hidden`), no generation is added, the control pair keeps advancing, the log says it
     once per pair, /metrics and `--diagnose` name the table; repairing it resumes by
     itself and the delta carries the row written while blocked;
  3. no policy for the reader at all: `hidden`, same behaviour;
  4. a RESTRICTIVE policy hiding some rows beside the bridge's own: `unverifiable`, the
     case a count comparison alone would miss when it hides the same rows either way;
  5. the policy changes WHILE a snapshot is being built: a lock held on the table the build
     reads after its policy check parks it there and `ALTER POLICY ... USING (false)` is
     issued. PostgreSQL 16 makes the change wait for the build, so the build publishes under
     the policy it was verified with and the next cadence blocks; on a server that lets it
     through, the recheck must block the build instead. Either way no snapshot read under a
     policy other than the verified one is published.

Usage:  set -a && . ./.env.bridge && set +a
        export BRIDGE_CDC_PUBLICATION=my_pub        # named, never guessed
        python scripts/scenarios/rls_visibility.py  (⚠️ owns the only bridge)
Needs `nats-server` on PATH, ZB_PSQL (or the native defaults) as the database admin, and
`zig-out/bin/bridge`. Cleans up its tables, rows and slot.
"""

import asyncio
import json
import os
import pathlib
import re
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request
from urllib.parse import urlparse

import msgpack
import nats

import zb

PUB = os.environ.get("BRIDGE_CDC_PUBLICATION", "")
OPEN = zb.TOPOLOGY["open_tenant"]
GEN_PREFIX = zb.TOPOLOGY["generations"]["bucket_prefix"]
TA, TB = "zbrls_a", "zbrls_b"
OK, BAD, EMPTY, TOMB = "zb_rls_ok", "zb_rls_bad", "zb_rls_empty", "zb_rls_tomb"
TABLES = (OK, BAD, EMPTY, TOMB)
PRINCIPALS = {"zbrls_pa": TA, "zbrls_pb": TB}
CADENCE = 5
ZSTD_MAGIC = b"\x28\xb5\x2f\xfd"


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def reader_role():
    return urlparse(os.environ["DATABASE_READER_URL"]).username


def zstd_decode(data):
    try:
        import zstandard  # type: ignore
        return zstandard.ZstdDecompressor().decompress(data, max_output_size=1 << 30)
    except ImportError:
        pass
    if not shutil.which("zstd"):
        sys.exit("chain objects are zstd frames: install the `zstd` CLI or `pip install zstandard`")
    r = subprocess.run(["zstd", "-d", "-c", "-q"], input=data, capture_output=True)
    if r.returncode != 0:
        raise ValueError(r.stderr.decode(errors="replace"))
    return r.stdout


def decode(body):
    if not body.startswith(ZSTD_MAGIC):
        raise ValueError(f"chain object is not a zstd frame (starts {body[:4]!r})")
    return msgpack.unpackb(zstd_decode(body), raw=False, strict_map_key=False)


def gens(table, tenant):
    """(gen, incarnation, has_full) of the pair's live generations, oldest first."""
    out = zb.psql("SELECT gen, incarnation, has_full FROM public.zebridge_generations "
                  f"WHERE tenant='{tenant}' AND tbl='{table}' AND retired_at IS NULL ORDER BY gen", quiet=True)
    rows = []
    for line in out.splitlines():
        g, i, f = line.split("|")
        rows.append((int(g), int(i), f == "t"))
    return rows


def top(table, tenant):
    g = gens(table, tenant)
    return g[-1][0] if g else 0


def blocked_series(port):
    """{(table, tenant): (verdict, 0|1)} from /metrics, only for this scenario's tables."""
    try:
        text = urllib.request.urlopen(f"http://127.0.0.1:{port}/metrics", timeout=5).read().decode()
    except OSError:
        return {}
    out = {}
    for m in re.finditer(r'^bridge_snapshot_rls_blocked\{table="([^"]*)",tenant="([^"]*)",verdict="([^"]*)"\} (\d)$', text, re.M):
        if m.group(1) in TABLES:
            out[(m.group(1), m.group(2))] = (m.group(3), int(m.group(4)))
    return out


def blocked_now(port, table):
    return {t: v for (tb, t), (v, on) in blocked_series(port).items() if tb == table and on == 1}


async def wait_for(pred, timeout, step=0.5):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if pred():
            return True
        await asyncio.sleep(step)
    return pred()


def touch(table, ids, mark):
    zb.psql(f"UPDATE public.{table} SET v = v || '{mark}', updated_at = now() WHERE id IN ({','.join(map(str, ids))})", quiet=True)


def fixtures(role):
    """Throwaway tables: OK and BAD tenant-scoped with rows for both tenants, EMPTY an
    untenanted table with no row at all, TOMB a tenant table whose only row is a tombstone."""
    for t in TABLES:
        zb.psql(f"DROP TABLE IF EXISTS public.{t} CASCADE", quiet=True)
        zb.psql(f"DELETE FROM public.zebridge_catalogue WHERE tbl = '{t}'", quiet=True)
        zb.psql(f"DELETE FROM public.zebridge_generations WHERE tbl = '{t}'", quiet=True)
    cols = "id int PRIMARY KEY, tenant_id text NOT NULL, v text NOT NULL DEFAULT '', " \
           "updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz, \"true\" boolean NOT NULL DEFAULT true"
    old = "now() - interval '1 minute'"
    for t in (OK, BAD):
        zb.psql(f"CREATE TABLE public.{t} ({cols})", quiet=True)
        zb.psql(f"INSERT INTO public.{t} (id, tenant_id, v, updated_at) VALUES "
                f"(1,'{TA}','a1',{old}),(2,'{TA}','a2',{old}),(3,'{TB}','b1',{old}),(4,'{TB}','b2',{old})", quiet=True)
    zb.psql(f"CREATE TABLE public.{TOMB} ({cols})", quiet=True)
    zb.psql(f"INSERT INTO public.{TOMB} (id, tenant_id, v, updated_at, deleted_at) VALUES (1,'{TA}','gone',{old},{old})", quiet=True)
    zb.psql(f"CREATE TABLE public.{EMPTY} (id int PRIMARY KEY, v text, updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz)", quiet=True)
    for principal, tenant in PRINCIPALS.items():
        zb.psql(f"INSERT INTO public.zebridge_user_tenants (principal, tenant_id) VALUES ('{principal}','{tenant}') ON CONFLICT DO NOTHING", quiet=True)
    for t in (OK, BAD, TOMB):
        r = zb.psql(f"SELECT status FROM zebridge_enable('public.{t}', writable => true, version_col => 'updated_at', "
                    f"tombstone_col => 'deleted_at', tenant_col => 'tenant_id', publication => '{PUB}', dry_run => false) "
                    "WHERE status = 'ERROR'", quiet=True)
        if r:
            sys.exit(f"zebridge_enable({t}) failed")
    r = zb.psql(f"SELECT status FROM zebridge_enable('public.{EMPTY}', writable => false, version_col => 'updated_at', "
                f"tombstone_col => 'deleted_at', public_reason => 'rls_visibility scenario fixture', publication => '{PUB}', "
                "dry_run => false) WHERE status = 'ERROR'", quiet=True)
    if r:
        sys.exit(f"zebridge_enable({EMPTY}) failed")


def teardown():
    for t in TABLES:
        zb.psql(f"DROP TABLE IF EXISTS public.{t} CASCADE", quiet=True)
        zb.psql(f"DELETE FROM public.zebridge_catalogue WHERE tbl = '{t}'", quiet=True)
        zb.psql(f"DELETE FROM public.zebridge_generations WHERE tbl = '{t}'", quiet=True)
    for principal in PRINCIPALS:
        zb.psql(f"DELETE FROM public.zebridge_user_tenants WHERE principal = '{principal}'", quiet=True)


class Hold:
    """A session holding ACCESS EXCLUSIVE on zebridge_gc_watermark. A foreground build reads
    that table AFTER its policy check and BEFORE its content, so while the lock is held a
    build is parked exactly between the two."""

    def __init__(self):
        self.p = subprocess.Popen(zb.PSQL.split() + ["-q"], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                                  stderr=subprocess.DEVNULL, text=True)
        self.p.stdin.write("BEGIN;\nLOCK TABLE public.zebridge_gc_watermark IN ACCESS EXCLUSIVE MODE;\n")
        self.p.stdin.flush()

    def release(self):
        try:
            self.p.stdin.write("ROLLBACK;\n\\q\n")
            self.p.stdin.flush()
        except OSError:
            pass
        try:
            self.p.wait(timeout=15)
        except subprocess.TimeoutExpired:
            self.p.kill()


def parked_table(role):
    """The fixture table whose build is parked on the held lock, or None."""
    pid = zb.psql(f"SELECT pid FROM pg_stat_activity WHERE usename = '{role}' AND wait_event_type = 'Lock' "
                  "AND query ILIKE '%zebridge_gc_watermark%' LIMIT 1", quiet=True)
    if not pid:
        return None
    names = ",".join(f"'{t}'" for t in (OK, BAD, TOMB))
    return zb.psql("SELECT c.relname FROM pg_locks l JOIN pg_class c ON c.oid = l.relation "
                   f"WHERE l.pid = {pid} AND l.granted AND l.mode = 'AccessShareLock' AND c.relkind = 'r' "
                   f"AND c.relname IN ({names}) LIMIT 1", quiet=True) or None


async def read_object(js, tenant, name):
    store = await js.object_store(f"{GEN_PREFIX}{tenant}")
    return decode((await store.get(name)).data)


async def rows_since(js, table, tenant, after_gen):
    """Every row value carried by the pair's generations newer than `after_gen`."""
    seen = []
    for g, inc, has_full in gens(table, tenant):
        if g <= after_gen:
            continue
        kinds = ["delta"] + (["full"] if has_full else [])
        for kind in kinds:
            try:
                doc = await read_object(js, tenant, f"{table}-i{inc}-g{g}-{kind}")
            except Exception:
                continue
            for row in doc.get("rows", []):
                seen.extend(str(x) for x in row)
    return seen


async def main():
    failed = 0

    def check(ok, label):
        nonlocal failed
        (zb.ok if ok else zb.bad)(label)
        failed += not ok

    if not PUB:
        sys.exit("BRIDGE_CDC_PUBLICATION is not set — the publication is named, never guessed")
    if not shutil.which("nats-server"):
        sys.exit("nats-server is not on PATH")
    if not zb.BRIDGE.exists():
        sys.exit(f"{zb.BRIDGE} not found — run `zig build bridge`")
    if zb.another_bridge_running():
        sys.exit("another bridge is already running — it would build these pairs concurrently; stop it first")
    role = reader_role()
    bridge_port = zb.bridge_port()

    with tempfile.TemporaryDirectory(prefix="zb-rls-") as folder:
        tmp = pathlib.Path(folder)
        ports = [free_port() for _ in range(3)]
        gen = subprocess.run([str(zb.BRIDGE), "--init-nats", "operator", "--dir", str(tmp / "hub"),
                              "--port", str(ports[0]), "--http-port", str(ports[1]), "--ws-port", str(ports[2])],
                             capture_output=True, text=True)
        assert gen.returncode == 0, gen.stderr
        conf = tmp / "hub" / "nats-server.conf"
        with conf.open("a") as f:
            f.write('\nhost: "127.0.0.1"\n')
        url = f"nats://127.0.0.1:{ports[0]}"
        creds = str(tmp / "hub" / "creds" / "bridge.creds")
        server = None
        nc = None
        try:
            with open(tmp / "nats.log", "w") as out:
                server = subprocess.Popen(["nats-server", "-c", str(conf)], stdout=out, stderr=out)
            for _ in range(100):
                try:
                    socket.create_connection(("127.0.0.1", ports[0]), timeout=0.2).close()
                    break
                except OSError:
                    await asyncio.sleep(0.1)

            fixtures(role)
            with zb.Bridge(tmp / "bridge.log", NATS_URL=url, NATS_CREDS=creds, NATS_JS_DOMAIN="", NATS_TLS_CA="",
                           GENERATIONS_ENABLED="1", GENERATION_CADENCE_SECONDS=str(CADENCE), LOG_LEVEL="info",
                           GENERATION_RULES=f"{OK}:{TA},{TB};{BAD}:{TA},{TB};{EMPTY}:{OPEN};{TOMB}:{TA}") as bridge:
                nc = await nats.connect(url, user_credentials=creds)
                js = nc.jetstream()
                pairs = [(OK, TA), (OK, TB), (BAD, TA), (BAD, TB), (EMPTY, OPEN), (TOMB, TA)]

                # ── 1. a valid configuration publishes, empty tables included ──────────────
                built = await wait_for(lambda: all(top(t, n) >= 1 for t, n in pairs), 60)
                check(built, "valid configuration: every pair builds its first generation")
                if not built:
                    print(bridge.text()[-2500:])
                    return failed + 1
                for table, tenant, label in ((EMPTY, OPEN, "an empty untenanted table"),
                                             (TOMB, TA, "a tenant pair whose only row is a tombstone")):
                    g, inc, has_full = gens(table, tenant)[0]
                    doc = await read_object(js, tenant, f"{table}-i{inc}-g{g}-full")
                    check(has_full and doc.get("kind") == "full" and doc.get("rows") == [],
                          f"{label} publishes an EMPTY full — empty is not blocked")
                check(not any(on for _, on in blocked_series(bridge_port).values()),
                      "nothing of this scenario's is blocked while the configuration is valid")

                async def case(name, break_sql, repair_sql, verdict, needle, ids, mark, with_diagnose=False):
                    """Break BAD's read policy after startup, prove the guard, repair, prove recovery."""
                    nonlocal failed
                    print(f"\n── {name}")
                    before = {t: top(BAD, t) for t in (TA, TB)}
                    ok_before = {t: top(OK, t) for t in (TA, TB)}
                    logged = bridge.text().count(f"'{TA}'/'{BAD}': publication BLOCKED")
                    for q in break_sql:
                        zb.psql(q, quiet=True)
                    touch(BAD, ids, mark)
                    touch(OK, (1, 3), mark)
                    named = await wait_for(lambda: set(blocked_now(bridge_port, BAD)) == {TA, TB}, 4 * CADENCE)
                    check(named, f"/metrics names both pairs of {BAD} as blocked (saw {sorted(blocked_now(bridge_port, BAD))})")
                    states = set(blocked_now(bridge_port, BAD).values())
                    check(states == {verdict}, f"verdict is '{verdict}' (saw {sorted(states)})")
                    advanced = await wait_for(lambda: all(top(OK, t) > ok_before[t] for t in (TA, TB)), 4 * CADENCE)
                    check(advanced, f"the control table keeps publishing while {BAD} is blocked (unrelated pairs continue)")
                    await asyncio.sleep(2 * CADENCE + 1)
                    check(all(top(BAD, t) == before[t] for t in (TA, TB)),
                          "no generation was added for the blocked pairs: the previous chain stays")
                    check(not blocked_now(bridge_port, OK), "the control pairs are not blocked")
                    text = bridge.text()
                    lines = [l for l in text.splitlines() if f"'{BAD}': publication BLOCKED" in l]
                    check(any(needle in l for l in lines), f"the log names the cause ({needle!r})")
                    check(text.count(f"'{TA}'/'{BAD}': publication BLOCKED") - logged == 1,
                          "the log says it once per pair, not at every cadence")
                    if with_diagnose:
                        env = zb.bridge_env(NATS_URL=url, NATS_CREDS=creds, NATS_JS_DOMAIN="", NATS_TLS_CA="")
                        d = subprocess.run([str(zb.BRIDGE), "--diagnose", "--slot", "zb_rls_diag", "--pub", PUB,
                                            "--port", str(free_port())], env=env, capture_output=True, text=True, timeout=120)
                        report = d.stdout + d.stderr
                        check(BAD in report and needle in report and d.returncode != 0,
                              "bridge --diagnose names the table, the cause, and exits non-zero")
                    for q in repair_sql:
                        zb.psql(q, quiet=True)
                    resumed = await wait_for(lambda: all(top(BAD, t) > before[t] for t in (TA, TB)) and not blocked_now(bridge_port, BAD), 6 * CADENCE)
                    check(resumed, "repairing the policy resumes publication by itself, no restart")
                    for tenant in (TA, TB):
                        seen = await rows_since(js, BAD, tenant, before[tenant])
                        check(any(mark in x for x in seen), f"the row written while blocked ({tenant}) rode the first generation after the repair")

                bad_ids = (1, 3)
                await case("ALTER POLICY ... USING (false), after the bridge started",
                           [f"ALTER POLICY zb_reader_all ON public.{BAD} USING (false)"],
                           [f"SELECT zebridge_scope_reads_by_tenant('public.{BAD}', 'tenant_id')"],
                           "hidden", "USING (false)", bad_ids, "+f", with_diagnose=True)
                await case("no policy for the reader at all",
                           [f"DROP POLICY zb_reader_all ON public.{BAD}"],
                           [f"SELECT zebridge_scope_reads_by_tenant('public.{BAD}', 'tenant_id')"],
                           "hidden", "no policy lets the reader SELECT", bad_ids, "+n")
                await case("a restrictive policy hiding only some rows, beside the bridge's own",
                           [f"CREATE POLICY zb_rls_only_a ON public.{BAD} AS RESTRICTIVE FOR SELECT TO {role} USING (v NOT LIKE 'b%')"],
                           [f"DROP POLICY zb_rls_only_a ON public.{BAD}"],
                           "unverifiable", "zb_rls_only_a", bad_ids, "+r")
                # A boolean column NAMED "true": PostgreSQL prints USING ("true") and it is a filter,
                # not the keyword. Row 2 is the one it hides from the reader.
                await case('a restrictive policy on a column named "true", hiding a row',
                           [f"CREATE POLICY zb_rls_col_true ON public.{BAD} AS RESTRICTIVE FOR SELECT TO {role} USING (\"true\")",
                            f"UPDATE public.{BAD} SET \"true\" = false WHERE id = 2"],
                           [f"DROP POLICY zb_rls_col_true ON public.{BAD}",
                            f"UPDATE public.{BAD} SET \"true\" = true WHERE id = 2"],
                           "unverifiable", "zb_rls_col_true", bad_ids, "+q", with_diagnose=True)

                async def midbuild():
                    """Park a build between its policy check and its content, then change the policy."""
                    nonlocal failed
                    print("\n── the policy changes while a build is parked between its check and its content")
                    table = None
                    hold = None
                    for _ in range(4):
                        # something to publish, so the parked build has a generation to cut
                        touch(BAD, (1, 3), "+m")
                        touch(OK, (1, 3), "+m")
                        touch(TOMB, (1,), "+m")
                        hold = Hold()
                        deadline = time.time() + 3 * CADENCE
                        while time.time() < deadline and table is None:
                            await asyncio.sleep(0.3)
                            table = parked_table(role)
                        if table:
                            break
                        hold.release()
                    check(table is not None, "a build is parked between its policy check and its content")
                    if table is None:
                        return
                    tenants = [t for t in (TA, TB) if gens(table, t)]
                    before = {t: top(table, t) for t in tenants}
                    alter = subprocess.Popen(zb.PSQL.split() + ["-q", "-c", f"ALTER POLICY zb_reader_all ON public.{table} USING (false)"],
                                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    await asyncio.sleep(3)
                    waits = alter.poll() is None
                    hold.release()
                    finished = await wait_for(lambda: alter.poll() is not None, 3 * CADENCE)
                    check(finished, "the policy change completes once the build is released")
                    if waits:
                        print("    (this server makes ALTER POLICY wait for a running build)")
                        check(True, "ALTER POLICY waited for the parked build: a policy cannot change under a snapshot that holds its table")
                        published = await wait_for(lambda: any(top(table, t) > before[t] for t in tenants), 3 * CADENCE)
                        check(published, "the parked build published, under the policy it was verified with")
                        # …and the very next check sees the new policy
                        nxt = await wait_for(lambda: bool(blocked_now(bridge_port, table)), 4 * CADENCE)
                        check(nxt and set(blocked_now(bridge_port, table).values()) == {"hidden"},
                              "the next cadence finds the new policy and blocks the pair (hidden)")
                    else:
                        print("    (this server let ALTER POLICY through while the build was parked)")
                        blocked = await wait_for(lambda: bool(blocked_now(bridge_port, table)), 4 * CADENCE)
                        check(blocked, "the recheck blocked the parked build: the policy moved under it")
                        pairs_blocked = set(blocked_now(bridge_port, table))
                        check(all(top(table, t) == before[t] for t in pairs_blocked), "nothing the parked build read was published")
                    zb.psql(f"SELECT zebridge_scope_reads_by_tenant('public.{table}', 'tenant_id')", quiet=True)
                    resumed = await wait_for(lambda: not blocked_now(bridge_port, table), 6 * CADENCE)
                    check(resumed, "repairing the policy resumes publication by itself")

                await midbuild()
        finally:
            if nc is not None:
                await nc.close()
            if server is not None:
                server.terminate()
                try:
                    server.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    server.kill()
            teardown()
            zb.psql("SELECT pg_drop_replication_slot('zb_probe') WHERE EXISTS "
                    "(SELECT 1 FROM pg_replication_slots WHERE slot_name = 'zb_probe' AND NOT active)", quiet=True)

    print("\nPASS" if failed == 0 else f"\nFAIL ({failed})")
    return failed


zb.run(main)
